const invoiceLanguageKey = "invoice-language";
const languageToggle = document.getElementById("invoice-language");
const isInvoicePreview = document.documentElement.hasAttribute("data-invoice-preview");
let invoiceLanguage;

function invoiceText(english) {
  return invoiceLanguage === "es" && Object.hasOwn(invoiceSpanish, english)
    ? invoiceSpanish[english]
    : english;
}

function invoiceErrorMessage(error, fallback) {
  return Object.hasOwn(invoiceSpanish, error.message) ? error.message : fallback;
}

function setInvoiceText(element, english) {
  element.dataset.i18n = english;
  element.textContent = invoiceText(english);
}

function renderInvoiceDate(element) {
  const date = new Date(element.dateTime + "T12:00:00");
  element.textContent = date.toLocaleDateString(invoiceLanguage + "-US", {
    year: "numeric", month: "long", day: "numeric",
  });
}

function translateInvoicePage(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    const label = invoiceText(element.dataset.i18n);
    element.textContent = element.dataset.invoiceNumber
      ? element.dataset.invoiceNumber + " - " + label
      : label;
  });
  const attributes = [
    ["data-i18n-placeholder", "placeholder"],
    ["data-i18n-label", "aria-label"],
    ["data-i18n-alt", "alt"],
  ];
  for (const [marker, attribute] of attributes) {
    root.querySelectorAll("[" + marker + "]").forEach((element) => {
      element.setAttribute(attribute, invoiceText(element.getAttribute(marker)));
    });
  }
  root.querySelectorAll("time[datetime]").forEach(renderInvoiceDate);
}

function applyInvoiceLanguage(language) {
  invoiceLanguage = language;
  document.documentElement.lang = language;
  languageToggle.lang = language === "es" ? "en" : "es";
  languageToggle.textContent = language === "es" ? "English" : "Español";
  translateInvoicePage();
}

function restoreInvoiceLanguage() {
  const saved = localStorage.getItem(invoiceLanguageKey);
  const language = saved === "en" || saved === "es"
    ? saved
    : (navigator.language.startsWith("es") ? "es" : "en");
  if (language !== invoiceLanguage) applyInvoiceLanguage(language);
}

languageToggle.addEventListener("click", function () {
  const language = invoiceLanguage === "es" ? "en" : "es";
  if (!isInvoicePreview) localStorage.setItem(invoiceLanguageKey, language);
  applyInvoiceLanguage(language);
});

if (isInvoicePreview) {
  applyInvoiceLanguage("en");
} else {
  window.addEventListener("pageshow", restoreInvoiceLanguage);
  window.addEventListener("storage", function (event) {
    if (event.key === invoiceLanguageKey || event.key === null) restoreInvoiceLanguage();
  });
  restoreInvoiceLanguage();
}
